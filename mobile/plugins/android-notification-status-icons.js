// The patch finds these by name (getIdentifier), which resource shrinking
// cannot see; this keeps them in a shrunk release.
const KEEP_XML = `<?xml version="1.0" encoding="utf-8"?>
<resources xmlns:tools="http://schemas.android.com/tools"
    tools:keep="@drawable/notification_status_*,@layout/notification_status*" />
`

/** Pure: every file this plugin writes, relative to app/src/main/res. */
function statusResourceFiles(projectRoot) {
  const files = {}
  for (const kind of ICON_KINDS) {
    const source = `${ICON_DIR}/${kind}.svg`
    const svg = fs.readFileSync(path.join(projectRoot, source), 'utf8')
    files[`drawable/${drawableName(kind)}.xml`] = svgToVectorDrawable(svg, source)
  }
  files['layout/notification_status.xml'] = statusLayoutXml({ expanded: false })
  files['layout/notification_status_big.xml'] = statusLayoutXml({ expanded: true })
  files['raw/notification_status_keep.xml'] = KEEP_XML
  return files
}

module.exports = function withAndroidNotificationStatusIcons(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res')
      for (const [file, contents] of Object.entries(statusResourceFiles(cfg.modRequest.projectRoot))) {
        fs.mkdirSync(path.dirname(path.join(res, file)), { recursive: true })
        fs.writeFileSync(path.join(res, file), contents)
      }
      return cfg
    }
  ])
}

module.exports.ICON_KINDS = ICON_KINDS
module.exports.drawableName = drawableName
module.exports.svgToVectorDrawable = svgToVectorDrawable
module.exports.statusLayoutXml = statusLayoutXml
module.exports.statusResourceFiles = statusResourceFiles
